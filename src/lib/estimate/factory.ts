function optionsFromRecord(record: Record<string, number>, labels?: Record<string, string>): SelectOption[] {
  return Object.entries(record).map(([id, value]) => ({
    id,
    label: labels?.[id] ?? id,
    value,
  }));
}

function computed(
  partial: Omit<Field, "type"> & { formula: string },
): Field {
  return {
    hidden: true,
    showInResults: true,
    showInPrint: true,
    ...partial,
    type: "computed",
  };
}

