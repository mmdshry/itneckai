function documentFromSchema(schema: FormSchema): FormDocument {
  const values: FormDocument["values"] = {};
  for (const field of schema.fields) {
    if (field.type === "computed") continue;
    values[field.id] = cloneJson(field.defaultValue);
  }
  return { schema, values };
}

export function factoryDocument(mode: EstimateMode): FormDocument {
  return documentFromSchema(mode === "advance" ? advanceSchema() : standardSchema());
}

export function factoryDraftDocuments(): {
  standard: FormDocument;
  advance: FormDocument;
} {
  return {
    standard: factoryDocument("standard"),
    advance: factoryDocument("advance"),
  };
}
